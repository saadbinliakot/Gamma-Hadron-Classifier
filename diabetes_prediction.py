def plot_history(history):
  fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4))
  ax1.plot(history.history['loss'], label='loss')
  ax1.plot(history.history['val_loss'], label='val_loss')
  ax1.set_xlabel('Epoch')
  ax1.set_ylabel('Binary crossentropy')
  ax1.grid(True)

  ax2.plot(history.history['accuracy'], label='accuracy')
  ax2.plot(history.history['val_accuracy'], label='val_accuracy')
  ax2.set_xlabel('Epoch')
  ax2.set_ylabel('Accuracy')
  ax2.grid(True)

  plt.show()

from sklearn.utils import class_weight

def train_model(X_train, Y_train, num_nodes, dropout_prob, lr, batch_size, epochs):
  class_weights_array = class_weight.compute_class_weight(
    class_weight='balanced',
    classes=np.unique(Y_train),
    y=Y_train
  )
  class_weights = dict(enumerate(class_weights_array))
  early_stop = EarlyStopping(
    monitor='val_loss',
    patience=5,
    restore_best_weights=True
  )
  nn_model = Sequential([
      Input(shape=(X_train.shape[1],)),
      Dense(num_nodes, activation='relu'),
      Dropout(dropout_prob),
      Dense(num_nodes, activation='relu'),
      Dropout(dropout_prob),
      Dense(1, activation='sigmoid')
  ])

  nn_model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=lr), loss='binary_crossentropy', metrics=['accuracy'])
  history = nn_model.fit(
    X_train, Y_train, epochs=epochs, batch_size=batch_size, validation_split=0.2, callbacks=[early_stop], class_weight=class_weights, verbose=0
  )

  return nn_model, history

